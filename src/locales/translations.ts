export function getTranslation(lang: string, key: keyof TranslationKeys): string {
  const langCode = (lang in translations ? lang : 'en') as LanguageCode;
  return translations[langCode][key] ?? translations.en[key];
}

export function isRTL(lang: string): boolean {
  return RTL_LANGUAGES.has(lang as LanguageCode);
}
